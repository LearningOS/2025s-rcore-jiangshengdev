//! [`TaskContext`] 的实现
//!
//! 任务上下文是任务切换时需要保存和恢复的寄存器状态
//! 在 RISC-V 中，包含返回地址、栈指针和被调用者保存的寄存器

use crate::trap::trap_return;

#[repr(C)]
/// 任务上下文结构，包含一些寄存器
///
/// 用于任务切换时保存CPU寄存器状态
/// 与 `switch.S` 中的汇编代码紧密相关，字段顺序必须匹配
/// 只保存了必要的几个寄存器，而不是所有寄存器

pub struct TaskContext {
    /// 任务切换后的返回位置
    /// 保存任务恢复执行时应该跳转的地址
    ra: usize,

    /// 栈指针
    /// 保存任务的栈顶地址
    sp: usize,

    /// s0-s11 寄存器，被调用者保存
    /// 在函数调用过程中需要由被调用函数保存的寄存器
    /// 在上下文切换时必须保存这些值
    s: [usize; 12],
}

impl TaskContext {
    /// 创建一个新的空任务上下文
    ///
    /// 所有寄存器值都初始化为0
    /// 通常在初始任务切换时使用，比如启动第一个任务
    ///
    /// # 返回值
    ///
    /// 返回一个所有字段初始化为0的空TaskContext

    pub fn zero_init() -> Self {

        // 创建一个全0的任务上下文
        Self {
            ra: 0,
            sp: 0,
            s: [0; 12],
        }
    }

    /// 创建一个带有陷阱返回地址和内核栈指针的新任务上下文
    ///
    /// 设置返回地址为陷阱返回函数，这样当任务被切换回来时
    /// 将跳转到trap_return函数，从而从内核态返回到用户态
    ///
    /// # 参数
    ///
    /// * `kstack_ptr` - 内核栈栈顶指针，用于设置sp寄存器
    ///
    /// # 返回值
    ///
    /// 返回一个初始化了ra和sp的任务上下文

    pub fn goto_trap_return(kstack_ptr: usize) -> Self {

        // 返回地址设置为trap_return函数，使切换回该上下文时执行trap_return
        // 栈指针设置为提供的内核栈指针
        // 其他s寄存器初始化为0
        Self {
            ra: trap_return as usize,
            sp: kstack_ptr,
            s: [0; 12],
        }
    }
}
