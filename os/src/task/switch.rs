//! `__switch` 的 Rust 封装。
//!
//! 任务上下文切换的实现。
//! 本模块实现了RISC-V架构下的任务切换机制，用于保存和恢复任务执行状态。
//! 切换到不同任务的上下文必须在汇编语言中实现，因为：
//! 1. 需要直接操作寄存器，这在Rust中无法安全地完成
//! 2. 任务切换过程中会改变栈指针，可能导致Rust的安全检查失效
//! 3. 需要精确控制哪些寄存器保存/恢复，以确保正确的上下文切换
//!
//! 因此，该模块只是对汇编实现(`switch.S`)的封装。

// 包含汇编代码文件
core::arch::global_asm!(include_str!("switch.S"));

use super::TaskContext;

extern "C" {

    /// 任务上下文切换函数
    ///
    /// 保存当前任务的上下文到current_task_cx_ptr指向的内存，
    /// 然后加载next_task_cx_ptr指向的上下文到CPU寄存器中继续执行。
    ///
    /// 这个函数在汇编中实现（switch.S），主要完成以下工作：
    /// 1. 保存被调用者保存的寄存器(s0-s11)到当前任务上下文
    /// 2. 保存ra和sp到当前任务上下文
    /// 3. 加载下一个任务上下文中的ra、sp和s寄存器
    /// 4. 跳转到下一个任务的返回地址(ra)继续执行
    ///
    /// # 参数
    ///
    /// * `current_task_cx_ptr` - 当前任务上下文的指针，用于保存当前状态
    /// * `next_task_cx_ptr` - 下一个任务上下文的指针，用于恢复新任务的状态
    ///
    /// # 安全性
    ///
    /// 这是一个不安全的外部函数调用，调用者必须确保：
    /// - 两个指针都指向有效的TaskContext结构
    /// - 指针对齐正确
    /// - 上下文切换不会破坏Rust的内存安全假设
    pub fn __switch(current_task_cx_ptr: *mut TaskContext, next_task_cx_ptr: *const TaskContext);

}
